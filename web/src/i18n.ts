// ---------- current language ----------
let cur: Lang = 'zh-CN'
const listeners = new Set<() => void>()

export const isLang = (x: unknown): x is Lang => typeof x === 'string' && (LANGS as readonly string[]).includes(x)
export const lang = (): Lang => cur
export function onLangChange(fn: () => void) {
  listeners.add(fn)
}

function apply() {
  if (typeof document === 'undefined') return
  try {
    document.title = t('doc.title')
    if (document.documentElement) document.documentElement.lang = cur
  } catch {
    /* the Node test DOM has none of this */
  }
}

/** Once on page load: ?lang= first, then localStorage, else zh-CN */
export function initLang(): Lang {
  let pick: Lang = 'zh-CN'
  try {
    const q = new URLSearchParams(globalThis.location?.search ?? '').get('lang')
    if (isLang(q)) pick = q
    else {
      const s = globalThis.localStorage?.getItem(LS_KEY)
      if (isLang(s)) pick = s
    }
  } catch {
    /* private mode etc.: default */
  }
  cur = pick
  apply()
  return cur
}

export function setLang(l: Lang, persist = true) {
  if (!isLang(l)) return
  cur = l
  apply()
  if (persist) {
    try {
      globalThis.localStorage?.setItem(LS_KEY, l)
    } catch {
      /* ignore */
    }
    // keep ?lang= in the address bar in step, so a reload keeps the language (no navigation)
    try {
      const u = new URL(location.href)
      if (u.searchParams.has('lang')) {
        u.searchParams.set('lang', l)
        history.replaceState(history.state, '', u)
      }
    } catch {
      /* ignore */
    }
  }
  for (const fn of listeners) fn()
}

export function cycleLang(): Lang {
  setLang(LANGS[(LANGS.indexOf(cur) + 1) % LANGS.length])
  return cur
}

// ---------- translation ----------
/** {name} is replaced by the param; {name|one|many} picks a word by the param's number (English plurals) */
function fill(l: Lang, s: string, p?: Record<string, Param>): string {
  if (!p) return s
  return s.replace(/\{(\w+)(?:\|([^|{}]*)\|([^|{}]*))?\}/g, (all, name: string, one?: string, many?: string) => {
    const v = p[name]
    if (v === undefined || v === null) return all
    if (one !== undefined) return Number(v) === 1 ? one : (many ?? '')
    return typeof v === 'object' ? tIn(l, v.k, v.p) : String(v)
  })
}

/** Translate in a given language (missing: zh-CN, then the key itself) */
export function tIn(l: Lang, key: string, p?: Record<string, Param>): string {
  return fill(l, DICT[l][key] ?? DICT['zh-CN'][key] ?? key, p)
}

/** Current language. Params go in as they are: the caller esc()s outside values that end up in innerHTML */
export function t(key: Key, p?: Record<string, Param>): string {
  return tIn(cur, key, p)
}
export const tm = (m: Msg): string => tIn(cur, m.k, m.p)

const tOr = (key: string, fallback: string): string => DICT[cur][key] ?? DICT['zh-CN'][key] ?? fallback
export const ruleText = (rule: string): string => tOr(`rule.${rule}`, rule)
export const ruleShortText = (rule: string): string => tOr(`ruleS.${rule}`, rule)
export const kindText = (kind: string): string => tOr(`kind.${kind}`, `kind ${kind}`)
export const cardDesc = (id: CardId): string => tOr(`card.${id}`, id)
